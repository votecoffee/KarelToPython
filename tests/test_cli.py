"""Real command-line translation, execution and source-preserving publication."""
import ast
from contextlib import redirect_stderr, redirect_stdout
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from karel2py import __version__, translate
from karel2py.__main__ import main

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'PROGRAM DEMO\nVAR n: INTEGER\nBEGIN\n  n=6*7\nEND DEMO\n'


class CommandLineTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)
        self.root = Path(self.folder.name)
        self.source, self.output, self.report = (self.root / name for name in ('source.kl', 'out.py', 'report.json'))
        self.source.write_bytes(SOURCE.encode())

    def cli(self, *args):
        return subprocess.run([sys.executable, '-X', 'utf8', '-m', 'karel2py', *map(str, args)],
                              cwd=ROOT, capture_output=True, text=True)

    def link(self, source, target):
        try: os.link(source, target)
        except OSError as exc: self.skipTest('Hard links unavailable: ' + str(exc))

    def test_check_bom_crlf_report_hashes_original_bytes_and_preserves_source(self):
        original = b'\xef\xbb\xbf' + SOURCE.replace('\n', '\r\n').encode()
        self.source.write_bytes(original)
        result = self.cli(self.source, '--check', '--report', self.report)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(result.stdout.startswith('DEMO: validated;'))
        self.assertEqual(result.stderr, 'KarelToPython ' + __version__ + '\n')
        report = json.loads(self.report.read_text())
        self.assertEqual(report['source_file_sha256'], hashlib.sha256(original).hexdigest())
        self.assertEqual(report['translator_version'], __version__)
        self.assertEqual(self.source.read_bytes(), original)
        self.assertFalse(self.output.exists())

    def test_generated_script_executes_as_a_separate_process(self):
        result = self.cli(self.source, '-o', self.output, '--report', self.report)
        self.assertEqual(result.returncode, 0, result.stderr)
        execution = subprocess.run([sys.executable, '-X', 'utf8', str(self.output)], cwd=self.root,
                                   env={**os.environ, 'PYTHONPATH': str(ROOT)}, capture_output=True, text=True)
        self.assertEqual(execution.returncode, 0, execution.stderr)
        self.assertEqual(ast.literal_eval(execution.stdout)['N'], 42)
        self.assertEqual(self.source.read_text(), SOURCE)

    def test_force_replaces_named_outputs_and_retains_source(self):
        self.output.write_text('old Python')
        self.report.write_text('old report')
        result = self.cli(self.source, '-o', self.output, '--report', self.report, '--force')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(self.output.read_text().startswith('# Generated by karel2py '))
        self.assertEqual(json.loads(self.report.read_text())['status'], 'translated')
        self.assertEqual(self.source.read_text(), SOURCE)
        self.assertEqual(list(self.root.glob('.*.tmp')), [])

    def test_existing_report_prevents_python_publication_without_force(self):
        self.report.write_text('keep')
        result = self.cli(self.source, '-o', self.output, '--report', self.report)
        self.assertEqual(result.returncode, 1)
        self.assertFalse(self.output.exists())
        self.assertEqual(self.report.read_text(), 'keep')

    def test_hardlinked_source_cannot_be_output_or_rejection_report(self):
        alias = self.root / 'alias'
        self.link(self.source, alias)
        for args in (('-o', alias), ('--check', '--report', alias)):
            with self.subTest(args=args):
                result = self.cli(self.source, *args, '--force')
                self.assertEqual(result.returncode, 2, result.stderr)
                self.assertIn('file aliases', result.stderr)
                self.assertEqual(self.source.read_text(), SOURCE)
                self.assertEqual(alias.read_text(), SOURCE)

    def test_output_and_report_cannot_be_hardlink_aliases(self):
        self.output.write_text('keep')
        self.link(self.output, self.report)
        result = self.cli(self.source, '-o', self.output, '--report', self.report, '--force')
        self.assertEqual(result.returncode, 2)
        self.assertEqual(self.output.read_text(), 'keep')
        self.assertEqual(self.report.read_text(), 'keep')

    def test_symlink_outputs_are_rejected_including_dangling_links(self):
        target = self.root / 'target'
        target.write_text('keep')
        try: self.output.symlink_to(target)
        except OSError as exc: self.skipTest('Symbolic links unavailable: ' + str(exc))
        result = self.cli(self.source, '-o', self.output, '--force')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(target.read_text(), 'keep')
        self.output.unlink()
        self.output.symlink_to(self.root / 'missing')
        result = self.cli(self.source, '-o', self.output, '--force')
        self.assertEqual(result.returncode, 1)
        self.assertFalse((self.root / 'missing').exists())

    def test_directory_target_fails_before_creating_other_output(self):
        result = self.cli(self.source, '-o', self.output, '--report', self.root, '--force')
        self.assertEqual(result.returncode, 1)
        self.assertFalse(self.output.exists())
        self.assertNotIn('Traceback', result.stderr)

    def test_input_encoding_and_missing_output_directory_use_io_exit_code(self):
        for invalid in (True, False):
            with self.subTest(invalid_encoding=invalid):
                self.source.write_bytes(b'\xff' if invalid else SOURCE.encode())
                output = self.output if invalid else self.root / 'missing' / 'out.py'
                result = self.cli(self.source, '-o', output)
                self.assertEqual(result.returncode, 1)
                self.assertFalse(output.exists())
                self.assertNotIn('Traceback', result.stderr)

    def test_rejection_emits_only_report_and_preserves_source(self):
        original = 'PROGRAM BAD BEGIN UNKNOWN END BAD'
        self.source.write_text(original)
        result = self.cli(self.source, '-o', self.output, '--report', self.report)
        self.assertEqual(result.returncode, 2)
        self.assertFalse(self.output.exists())
        report = json.loads(self.report.read_text())
        self.assertEqual(report['status'], 'rejected')
        self.assertEqual(report['diagnostics'][0]['line'], 1)
        self.assertEqual(self.source.read_text(), original)

    def test_invalid_cli_arguments_do_not_publish_outputs(self):
        cases = [('--check', '-o', self.output),
                 ('--check', '--array-shape', 'DATA=2', '--array-shape', 'data=3'),
                 ('-o', self.output, '--report', self.output, '--force')]
        for args in cases:
            with self.subTest(args=args):
                result = self.cli(self.source, *args)
                self.assertEqual(result.returncode, 2)
                self.assertFalse(self.output.exists())
                self.assertFalse(self.report.exists())

    def test_cli_runs_with_gui_imports_explicitly_blocked(self):
        probe = """import builtins,sys
sys.path.insert(0,sys.argv[1])
original=builtins.__import__
def headless(name,*args,**kwargs):
    if name=='tkinter' or name.startswith('tkinter.') or name=='karel2py.gui':
        raise AssertionError('CLI imported a desktop module')
    return original(name,*args,**kwargs)
builtins.__import__=headless
from karel2py.__main__ import main
code=main([sys.argv[2],'--check'])
assert not any(name=='tkinter' or name.startswith('tkinter.') for name in sys.modules)
raise SystemExit(code)
"""
        result = subprocess.run([sys.executable, '-I', '-c', probe, str(ROOT), str(self.source)],
                                cwd=self.root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('DEMO: validated;', result.stdout)

    def test_failed_replacement_keeps_old_output_and_cleans_temporary(self):
        self.output.write_text('keep')
        with patch('karel2py.fileio.os.replace', side_effect=OSError('locked')):
            with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()) as errors:
                code = main([str(self.source), '-o', str(self.output), '--force'])
        self.assertEqual(code, 1)
        self.assertIn('locked', errors.getvalue())
        self.assertEqual(self.output.read_text(), 'keep')
        self.assertEqual(list(self.root.glob('.*.tmp')), [])

    def test_source_alias_is_rechecked_when_publishing_after_translation(self):
        def changed_target(*args, **kwargs):
            result = translate(*args, **kwargs)
            self.link(self.source, self.output)
            return result
        with patch('karel2py.__main__.translate', side_effect=changed_target):
            with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
                code = main([str(self.source), '-o', str(self.output), '--force'])
        self.assertEqual(code, 1)
        self.assertEqual(self.source.read_text(), SOURCE)


if __name__ == '__main__': unittest.main()
