"""Emit the generated Program class metadata, runtime state, and entry points."""
from . import __version__
from .syntax import Statement


class ProgramLowering:
    """Bind checked declarations to the synchronous and cooperative runtime."""

    def emit_program_class(self):
        self.line(f'# Generated by karel2py {__version__}; offline prototype, not controller-equivalence proof.')
        self.line('from karel2py import runtime as _rt')
        self.line()
        self.line('class Program:')
        self.indent = 1
        self._emit_program_metadata()
        self._emit_program_constructor()
        self._emit_program_properties()

    def _emit_program_metadata(self):
        program = self.program
        self.line(f'source_program = {program.name!r}')
        self.line(f'translation_mode = {self.mode!r}')
        directives = tuple((row['name'], row['argument']) for row in program.directive_metadata)
        self.line(f'source_directives = {directives!r}')
        declarations = tuple((row['owner'], row['name'], row['pool'], row['line'], row['column'])
                             for row in program.storage_declarations)
        self.line(f'source_storage_declarations = {declarations!r}')
        if program.storage_declarations:
            self.features.add('VAR storage clause')
        groups = tuple(sorted({row['group'] for row in self.group_uses}))
        self.line(f'source_groups = {groups!r}')
        self.line(f'imported_variables = {tuple(program.imported_variables)!r}')
        self.line(f'imported_types = {tuple((row["name"], row["owner"]) for row in program.imported_types)!r}')
        owners = dict.fromkeys(self.user_types, program.name)
        owners.update((row['name'], row['owner']) for row in program.imported_types)
        self.line(f'type_owners = {owners!r}')
        if program.imported_types:
            self.features.add('source-linked TYPE FROM declaration')
        interfaces = {routine.name: dict(parameters=tuple(spec for _, spec in routine.parameters),
                                        result=routine.return_type, external=routine.external)
                      for routine in program.routines}
        self.line(f'routine_interfaces = {interfaces!r}')
        self.line(f'external_array_shapes = {tuple(self.array_shapes.items())!r}')
        self.line(f'variable_types = {self.user_types!r}')
        if self.mode == 'pythonic':
            self.line('input_analysis = None')
            self.line('input_analysis_sha256 = None')

    def _emit_program_constructor(self):
        self.line(f'@_rt._with_numeric_mode({self.mode!r})')
        self.line('def __init__(self, *, sleep=None, write=None, read=None, joint_axes=None, pose_tolerance=None, external_tolerance=None, clock_us=None, registers=None, context=None):')
        self.indent = 2
        self.line(f'self._state = _rt.State({self.types!r}, {self.constants!r}, sleep=sleep, write=write, read=read, joint_axes=joint_axes, pose_tolerance=pose_tolerance, external_tolerance=external_tolerance, clock_us=clock_us, registers=registers, context=context)')
        self.line(f'self._state.program_name={self.program.name!r}')
        self.line('self._state.program=self')
        self.line('if len(self.source_groups)==1: self._state.robot_group=self.source_groups[0]')
        if self.mode == 'pythonic':
            self.line('_rt.configure_task(self._state,self.source_directives)')
        self.line('self._state.execution.variables.attach(self.source_program,self._state)')
        self.indent = 1

    def _emit_program_property(self, name, value):
        self.line('@property')
        self.line(f'def {name}(self):')
        self.indent = 2
        self.line(f'return {value}')
        self.indent = 1

    def _emit_program_properties(self):
        for name, value in (
            ('source_settings', 'self._state._source_settings.copy()'),
            ('pose_tolerance', 'self._state.pose_tolerance'),
            ('write_requests', 'tuple(request.copy() for request in self._state.write_requests)'),
            ('read_requests', 'self._state.read_observations()'),
            ('clock_reads', 'tuple(observation.copy() for observation in self._state.clock_reads)'),
            ('register_requests', 'tuple(request.copy() for request in self._state.register_requests)'),
        ):
            self.line()
            self._emit_program_property(name, value)
        self._emit_program_property('service_requests', 'tuple(request.copy() for request in self._state.service_requests)')
        self.line()
        self._emit_program_property('task_settings', '_rt.task_root(self._state)._task_settings.copy()')
        self._emit_program_property('task_trace', 'tuple(row.copy() for row in _rt.task_root(self._state)._task_trace)')
        self.line()
        self._emit_program_property('abort_info', 'self._state.abort_info')
        self.line()
        self.line('def snapshot(self):')
        self.indent = 2
        self.line('return self._state.snapshot()')
        self.indent = 1

    def _emit_cooperative_methods(self):
        for signature, body, numeric in (
            ('run(self, *, max_steps=100000)', 'return _rt.run_cooperative(self,max_steps)', True),
            ('resume(self)', 'return _rt.resume_cooperative(self)', True),
            ('powerup(self)', 'return _rt.powerup_cooperative(self)', True),
            ('pause(self)', "_rt.request_task_control(self._state,'PAUSE')", False),
            ('stop(self)', 'return _rt.stop_cooperative(self)', False),
        ):
            if numeric:
                self.line(f'@_rt._with_numeric_mode({self.mode!r})')
            self.line(f'def {signature}:')
            self.indent = 2
            self.line(body)
            self.indent = 1
        self._emit_program_property('task_state', 'self._state.task_state')

    def emit_program_entry(self):
        self.line()
        sync_entry = self.mode == 'pythonic' and not self.cooperative
        if self.cooperative:
            self._emit_cooperative_methods()
        self._emit_execution_body(sync_entry)
        if sync_entry:
            self._emit_sync_run()

    def emit_program_return(self, operand, token):
        if self.mode != 'pythonic':
            self.error('E_RETURN', 'RETURN is only implemented inside routines', token)
        if operand is not None:
            self.error('E_RETURN', 'Main program RETURN cannot return a value', token)
        self.features.add('main program RETURN')
        if self.active_counters:
            self.features.add('RETURN from FOR with counter cleanup')
        self.line('raise _rt._ProgramReturn', token)

    def _emit_execution_body(self, sync_entry):
        direct_entry = not self.cooperative and not sync_entry
        has_program_return = self.mode == 'pythonic' and any(
            isinstance(node, Statement) and node.kind == 'return'
            for node in self.walk_nodes(self.program.body)
        )
        self.line(f'@_rt._with_numeric_mode({self.mode!r})')
        if self.cooperative:
            self.line('def _execute(self):')
        elif sync_entry:
            self.line('def _execute_sync(self):')
        else:
            self.line('def run(self, *, max_steps=100000):')
        self.indent = 2
        if self.cooperative:
            self.line('if False: yield None')
        if direct_entry:
            self.line('self._state.begin(max_steps)')
            self.line('self._state._driving=True')
        if self.cooperative or direct_entry or has_program_return:
            self.line('try:')
            self.indent += 1
        self.emit_body(self.program.body)
        if self.cooperative or has_program_return:
            self.indent -= 1
        if has_program_return:
            # Take the result after inner finally blocks have cleared active counters.
            self.line('except _rt._ProgramReturn:')
            self.indent += 1
            self.line('pass')
            self.indent -= 1
        if self.cooperative:
            self.line('except _rt.KarelRuntimeError as _failure:')
            self.indent += 1
            self.line('yield from _rt.runtime_failure(self._state,_failure)')
            self.line('raise')
            self.indent -= 1
        self.line('return self._state.snapshot()')
        if direct_entry:
            self.indent -= 1
            self.line('finally:')
            self.indent += 1
            self.line('self._state._driving=False')
            self.line('self._state.finish_teach_programs()')

    def _emit_sync_run(self):
        self.indent = 1
        self.line()
        self.line(f'@_rt._with_numeric_mode({self.mode!r})')
        self.line('def run(self, *, max_steps=100000):')
        self.indent = 2
        self.line('self._state.begin(max_steps)')
        self.line('self._state._driving=True')
        self.line('_completed = False')
        self.line('try:')
        self.indent = 3
        self.line('_result = self._execute_sync()')
        self.line('_completed = True')
        self.line('return _result')
        self.indent = 2
        self.line('finally:')
        self.indent = 3
        self.line('self._state._driving=False')
        self.line('self._state.finish_teach_programs(interrupted=not _completed)')

    def emit_program_runtime_metadata(self):
        self.indent = 1
        if self.mode == 'pythonic' and self.program.routines:
            counter_roots = {routine.name: set() for routine in self.program.routines if not routine.external}
            for use in self.reference_for_uses:
                if use['body'] in counter_roots and use['root'] is not None:
                    counter_roots[use['body']].add(use['root'])
            roots = {name: tuple(sorted(active)) for name, active in counter_roots.items()}
            self.line(f'local_for_roots = {roots!r}')
        if self.mode == 'pythonic' and self.cooperative:
            self.line(f'source_checkpoints = {tuple(sorted(self.source_checkpoints))!r}')
            self.line(f'skippable_checkpoints = {tuple(sorted(self.skippable_checkpoints))!r}')
